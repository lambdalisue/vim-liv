-- liv.generator.function.format — emit a LuaLS annotation file from parsed
-- function entries (pure Lua). Groups arity variants per name and merges them
-- into one typed @field. Param types are `any` (the help does not type params);
-- only names + optionality + the unioned return type are carried.

local M = {}

local KEYWORDS = {}
for word in
  (
    "and break do else elseif end false for function goto if in local nil "
    .. "not or repeat return then true until while"
  ):gmatch("%S+")
do
  KEYWORDS[word] = true
end

local function safe(name)
  return KEYWORDS[name] and (name .. "_") or name
end

-- Merge arity variants of one function: superset params (longest list), a param
-- is required only up to the smallest required-count across variants; the return
-- type is the sorted union of variant return types.
local function merge(variants)
  local min_required = math.huge
  local longest = {}
  local rettypes, seen = {}, {}
  for _, v in ipairs(variants) do
    local required = 0
    for _, p in ipairs(v.params) do
      if not p.optional then
        required = required + 1
      end
    end
    min_required = math.min(min_required, required)
    if #v.params > #longest then
      longest = v.params
    end
    if not seen[v.rettype] then
      seen[v.rettype] = true
      rettypes[#rettypes + 1] = v.rettype
    end
  end
  local params = {}
  for i, p in ipairs(longest) do
    params[i] = { name = p.name, optional = i > min_required }
  end
  table.sort(rettypes)
  return { params = params, rettype = table.concat(rettypes, "|") }
end

local function signature(m)
  local parts = {}
  for _, p in ipairs(m.params) do
    parts[#parts + 1] = safe(p.name) .. (p.optional and "?" or "") .. ": any"
  end
  return string.format("fun(%s): %s", table.concat(parts, ", "), m.rettype)
end

---@param entries liv.generator.function.Entry[] Parsed function entries.
---@param class_name string LuaLS class name to declare in the annotations.
---@return string annotations A LuaLS `---@meta` file declaring `class_name`'s fields.
function M.format(entries, class_name)
  local groups, order = {}, {}
  for _, e in ipairs(entries) do
    if not groups[e.name] then
      groups[e.name] = {}
      order[#order + 1] = e.name
    end
    table.insert(groups[e.name], e)
  end
  table.sort(order)

  local out =
    { "---@meta", "-- GENERATED by liv.generator -- do not edit.", "", "---@class " .. class_name }
  for _, name in ipairs(order) do
    out[#out + 1] = string.format("---@field %s %s", name, signature(merge(groups[name])))
  end
  return table.concat(out, "\n") .. "\n"
end

return setmetatable(M, {
  __call = function(_, entries, class_name)
    return M.format(entries, class_name)
  end,
})
