-- L1 self-test for the expanded liv.tester matchers (spec 0010).
-- Exercises each matcher directly (no nested run) so it never perturbs the
-- surrounding suite's pass/fail counts. Failure-path cases assert *that* the
-- matcher raises (via the existing has_error) and *what* the message says.
local tester = require("liv.tester")
local A = tester.assert

describe("liv.tester matchers", function()
  describe("match", function()
    it("accepts a value matching the Lua pattern", function()
      A.match("hello world", "wor%a+")
    end)

    it("rejects a value that does not match", function()
      A.has_error(function()
        A.match("hello", "%d+")
      end)
    end)

    it("reports the pattern and value on failure", function()
      local err = A.has_error(function()
        A.match("abc", "%d+")
      end)
      assert.is_not_nil(tostring(err):find("%d+", 1, true))
      assert.is_not_nil(tostring(err):find("abc", 1, true))
    end)
  end)

  describe("length_of", function()
    it("accepts a sequence of the expected length", function()
      A.length_of({ 1, 2, 3 }, 3)
    end)

    it("accepts a string of the expected length", function()
      A.length_of("abcd", 4)
    end)

    it("rejects a wrong length and shows expected vs got", function()
      local err = A.has_error(function()
        A.length_of({ 1, 2 }, 3)
      end)
      assert.is_not_nil(tostring(err):find("3", 1, true))
      assert.is_not_nil(tostring(err):find("2", 1, true))
    end)
  end)

  describe("includes / contains", function()
    it("finds a value in a sequence", function()
      A.includes({ "a", "b", "c" }, "b")
    end)

    it("contains is an alias of includes", function()
      A.contains({ 1, 2, 3 }, 2)
    end)

    it("finds a substring in a string", function()
      A.includes("hello world", "world")
    end)

    it("rejects an absent element", function()
      A.has_error(function()
        A.includes({ 1, 2, 3 }, 9)
      end)
    end)

    it("rejects an absent substring", function()
      A.has_error(function()
        A.includes("hello", "zzz")
      end)
    end)
  end)

  describe("truthy / falsy", function()
    it("truthy accepts any non-false, non-nil value (distinct from is_true)", function()
      A.truthy(1)
      A.truthy("x")
      A.truthy({})
    end)

    it("truthy rejects nil and false", function()
      A.has_error(function()
        A.truthy(nil)
      end)
      A.has_error(function()
        A.truthy(false)
      end)
    end)

    it("falsy accepts nil and false", function()
      A.falsy(nil)
      A.falsy(false)
    end)

    it("falsy rejects a truthy value", function()
      A.has_error(function()
        A.falsy(0)
      end)
    end)
  end)

  describe("has_no_error", function()
    it("accepts a function that does not error and returns its value", function()
      local v = A.has_no_error(function()
        return 42
      end)
      assert.equal(42, v)
    end)

    it("rejects a function that raises, surfacing the error", function()
      local err = A.has_error(function()
        A.has_no_error(function()
          error("boom")
        end)
      end)
      assert.is_not_nil(tostring(err):find("boom", 1, true))
    end)
  end)

  describe("has_error with a pattern", function()
    it("keeps plain-substring behavior for has_error(fn, expected)", function()
      A.has_error(function()
        error("boom: detail")
      end, "boom")
    end)

    it("matches the message against a Lua pattern via has_error_matching", function()
      A.has_error_matching(function()
        error("code 404 not found")
      end, "%d%d%d")
    end)

    it("rejects when the pattern does not match the message", function()
      A.has_error(function()
        A.has_error_matching(function()
          error("plain text", 0)
        end, "%d+")
      end)
    end)
  end)
end)
